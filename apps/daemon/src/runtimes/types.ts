/**
 * Runtime agent definitions — declarative description of a local agent CLI.
 * Simplified port of open-design's apps/daemon/src/runtimes/types.ts.
 */

import type { DaemonAgentPayload } from '@remixclip/contracts';

import type { AgentAuthStatus, AgentCapability, AgentDiagnostic } from '@remixclip/contracts';

/**
 * Normalized set of capability names (discovered by probing `--help`). null = not probed /
 * probe failed; in that case every capability check is treated as "supported", keeping argv
 * consistent with the old behavior.
 */
export type AgentCapabilitySet = ReadonlySet<string> | null;

/**
 * Capability check: only downgrade when a capability is explicitly probed as missing;
 * unprobed (null) counts as supported, so a failed probe never degrades a usable agent.
 */
export function agentSupports(
  capabilities: AgentCapabilitySet | undefined,
  capabilityId: string,
): boolean {
  if (!capabilities) return true;
  return capabilities.has(capabilityId);
}

/** Auth probe description: one lightweight command + result classification rules. */
export interface AgentAuthProbe {
  /** Probe command args, e.g. `['auth', 'status']` / `['login', 'status']`. */
  args: string[];
  timeoutMs?: number;
  /** Matching these keywords in the output also counts as unauthenticated (even with exit code 0). */
  unauthenticatedHints?: string[];
  /**
   * Exact classification (optional): CLIs that emit parseable JSON use it for a definite verdict;
   * returning null means "inconclusive probe", which falls back to keywords + exit code.
   */
  classify?(result: { code: number | null; stdout: string; output: string }):
    | { status: 'ok' | 'unauthenticated' | 'unknown'; detail?: string }
    | null;
}

export interface AgentBuildArgsOptions {
  model?: string | null;
  /** Durable session handle passed in when resuming the upstream session (null when unsupported). */
  resumeSessionId?: string | null;
  /**
   * Full prompt for this turn. buildArgs only reads it when the agent goes via argv
   * (promptViaStdin=false and promptViaFile=false) or needs to encode it itself;
   * agents going via stdin / file / ACP can ignore it.
   */
  prompt?: string;
  /** Absolute path of the prompt temp file the daemon pre-wrote when promptViaFile=true. */
  promptFilePath?: string;
  /** Session id generated by the daemon for a new session (used by CLIs supporting --session-id). */
  newSessionId?: string;
  /** The agent's working directory (some CLIs need an explicit --dir/--workspace arg). */
  cwd?: string | null;
  /**
   * Capabilities probed from `--help` (passed along from the daemon's probe cache).
   * def uses it to decide whether to pass a flag, instead of hardcoding "which version supports
   * what" in code.
   */
  capabilities?: AgentCapabilitySet;
}

/**
 * Output protocol:
 * - ndjson       line-by-line JSON parsing (claude / codex / opencode / copilot / qoder / ...)
 * - plain        raw plain text (aider / deepseek / gemini / pi / ...)
 * - acp          bidirectional JSON-RPC session (hermes / kimi / kiro / ...)
 * - dsh-profile  DeepSeek Harness profile stdio protocol (structured frames + execute command)
 */
export type AgentStreamFormat = 'ndjson' | 'plain' | 'acp' | 'dsh-profile';

/** Optional behavior switches for the ACP adapter. */
export interface AgentAcpOptions {
  /** Treat an explicit turn_end update as this turn's terminal state (kiro etc.). */
  completePromptOnTurnEnd?: boolean;
  /** Format of mcpServers[].env in session/new (reasonix ≥1.0 uses map). */
  envFormat?: 'array' | 'map';
}

export interface RuntimeAgentDef {
  id: string;
  name: string;
  bin: string;
  /** Alternative binary names (tried in order when the primary bin is not found). */
  fallbackBins?: string[];
  /**
   * Candidate absolute paths of CLIs bundled inside an app package (`~/` expansion supported).
   * Tried only after PATH fails — for cases like the codex bundled in ChatGPT.app,
   * i.e. "GUI-installed apps that ship a CLI".
   */
  bundleBins?: string[];
  /** Env var that overrides the binary path (e.g. CLAUDE_BIN). */
  binEnvOverride?: string;
  versionArgs: string[];
  /** Recommended model list (CLI aliases/model ids, optional; for the frontend dropdown + custom input). */
  models?: string[];
  /**
   * Args for the capability-probing `--help` call (e.g. claude needs `['-p', '--help']` to list
   * the non-interactive flags). Defaults to `['--help']` when capabilityFlags is declared but
   * helpArgs is not.
   */
  helpArgs?: string[];
  /**
   * Capability table: key = flag that should appear in the CLI help, value = normalized capability
   * name. Each is looked up in the `--help` output during probing; only matches appear in the
   * detection result.
   */
  capabilityFlags?: Record<string, string>;
  /** Auth probe (optional): one lightweight command to determine login state, avoiding the
   *  45s connectivity test for trial-and-error. */
  authProbe?: AgentAuthProbe;
  /**
   * Fetch the real model list at runtime (e.g. codex's `debug models`).
   * Fails back to the static `models` when probing fails or returns empty.
   */
  listModels?: {
    args: string[];
    parse(stdout: string): string[];
    timeoutMs?: number;
  };
  /** Install docs link (optional; used by the diagnostic row's "install" button). */
  docsUrl?: string;
  /** Output protocol. */
  streamFormat: AgentStreamFormat;
  buildArgs(options: AgentBuildArgsOptions): string[];
  /** When true the prompt is written to child stdin instead of argv.
   *  (under acp / dsh-profile the prompt travels as protocol messages; this field is unused) */
  promptViaStdin: boolean;
  /**
   * When true the daemon writes the composed prompt to a temp file and passes
   * its path through buildArgs(runtimeContext.promptFilePath) — for CLIs whose
   * headless mode only accepts `--prompt-file <PATH>` (atomcode / grok-build).
   * Takes precedence over promptViaStdin.
   */
  promptViaFile?: boolean;
  /**
   * Custom stdin prompt encoding (antigravity needs a single NDJSON user-message frame).
   * Only takes effect when promptViaStdin=true.
   */
  encodeStdinPrompt?: (prompt: string) => string;
  /** Fixed env vars bundled with the adapter (e.g. reasonix's REASONIX_HOME). */
  env?: Record<string, string>;
  /**
   * Prompt byte limit for argv-style adapters (Windows CreateProcess ≈32KB /
   * Linux MAX_ARG_STRLEN). When exceeded, createRun reports an actionable error
   * instead of letting spawn fail with ENAMETOOLONG/E2BIG.
   */
  maxPromptArgBytes?: number;
  /** ACP adapter behavior switches. */
  acp?: AgentAcpOptions;
  /**
   * Create a stateful parser that maps one stdout line (NDJSON or plain
   * text, depending on the agent) to zero or more agent events.
   *  Only needed for the ndjson/plain formats.
   */
  createParser?(): (line: string) => DaemonAgentPayload[];
  /**
   * Extract the agent-side durable session handle from one stdout line (e.g. the session_id of
   * claude's stream-json init frame). Returning null means the line carries no session handle.
   * Only needed for the ndjson format; the session bridge captures it for acp / dsh-profile.
   */
  sessionIdFromLine?(line: string): string | null;
}

export interface DetectedAgent {
  id: string;
  name: string;
  bin: string;
  available: boolean;
  version?: string;
  path?: string;
  /** Binary source: standalone PATH install / bundled in app package. */
  binSource?: 'path' | 'app-bundle';
  error?: string;
  envKeys?: string[];
  models?: string[];
  docsUrl?: string;
  diagnostic?: AgentDiagnostic;
  /** Capabilities actually declared by `--help`. */
  capabilities?: AgentCapability[];
  /** authProbe verdict. */
  auth?: AgentAuthStatus;
}
